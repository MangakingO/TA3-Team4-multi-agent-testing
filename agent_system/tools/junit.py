"""Writes the curated test cases (test-cases.json) as one JUnit 5 test class."""
from __future__ import annotations

import re
import textwrap


def method_name(test_id: str) -> str:
    cleaned = re.sub(r"\W+", "_", test_id).strip("_")
    return "tc_" + (cleaned or "unnamed")


def body_of(junit: str) -> str:
    """The model may return statements or a whole @Test method; keep only the statements."""
    code = (junit or "").strip()
    fence = re.match(r"^```(?:java)?\s*(.*?)```$", code, re.S)
    if fence:
        code = fence.group(1).strip()
    if re.search(r"@Test\b|^\s*(?:public\s+|private\s+)?void\s+\w+\s*\([^)]*\)\s*(?:throws[\w\s,.]+)?\{", code, re.M):
        start, end = code.find("{"), code.rfind("}")
        if 0 <= start < end:
            code = code[start + 1:end]
    return textwrap.dedent(code).strip("\n").rstrip()


def _java_string(text: str, limit: int = 240) -> str:
    text = " ".join(text.split())
    if len(text) > limit:
        text = text[:limit - 3] + "..."
    return text.replace("\\", "\\\\").replace('"', '\\"')


def display_name(case: dict) -> str:
    extra = f" (also {', '.join(case['also'])})" if case.get("also") else ""
    return f"{case['id']} [{case.get('technique', '')}] {case.get('condition', '')}{extra} | {case.get('input', '')} -> {case.get('expected', '')}"


def track_new(code: str, class_name: str) -> str:
    """Wrap every `new ClassName(...)` in TestSupport.track(...), so its timers are stopped after the test."""
    pattern = re.compile(rf"(?<![\w.$])new\s+{re.escape(class_name)}\s*\(")
    out, i = [], 0
    while True:
        m = pattern.search(code, i)
        if not m:
            out.append(code[i:])
            return "".join(out)
        start = m.start()
        depth, j = 0, m.end() - 1
        while j < len(code):
            if code[j] == "(":
                depth += 1
            elif code[j] == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        k = j + 1
        while k < len(code) and code[k] in " \t\r\n":
            k += 1
        wrapped = re.search(r"track\(\s*$", code[max(0, start - 30):start]) is not None
        anonymous = k < len(code) and code[k] == "{"
        if wrapped or anonymous or j >= len(code):
            out.append(code[i:j + 1])
        else:
            out.append(code[i:start] + "TestSupport.track(" + code[start:j + 1] + ")")
        i = j + 1


FIXTURE = """\
    @BeforeEach
    void restoreStaticState() throws Exception {{
        TestSupport.restoreStatics({cls}.class);
    }}

    @AfterEach
    void stopTimers() {{
        TestSupport.cleanUp();
    }}"""


def render(class_name: str, package: str, cases: list[dict], timeout_seconds: int = 10) -> tuple[str, list[tuple[int, int, str]]]:
    """Return the Java source and a map (first line, last line, test id) used to blame compile errors."""
    out: list[str] = [
        "// Generated by the TA3 multi-agent system from test-cases.json; edit that file, not this one.",
        f"// Every new {class_name}(...) is wrapped in TestSupport.track(...) so its timers are stopped after the test.",
    ]
    if package:
        out += [f"package {package};", ""]
    out += [
        "import static org.junit.jupiter.api.Assertions.*;",
        "",
        "import java.io.*;",
        "import java.util.*;",
        "import org.junit.jupiter.api.*;",
        "",
        f"@Timeout({timeout_seconds})",
        f'@DisplayName("{class_name}: equivalence partitioning, boundary value and coverage tests")',
        f"class {class_name}Test {{",
        "",
        *FIXTURE.format(cls=class_name).splitlines(),
    ]
    line_map: list[tuple[int, int, str]] = []
    for case in cases:
        out.append("")
        first = len(out) + 1
        out.append("    @Test")
        out.append(f'    @DisplayName("{_java_string(display_name(case))}")')
        out.append(f"    void {method_name(case['id'])}() throws Exception {{")
        body = track_new(body_of(case.get("junit", "")), class_name) or "fail(\"empty test body\");"
        for line in body.splitlines():
            out.append(("        " + line) if line.strip() else "")
        out.append("    }")
        line_map.append((first, len(out), case["id"]))
    out.append("}")
    return "\n".join(out) + "\n", line_map


def blame(line_map: list[tuple[int, int, str]], line: int) -> str | None:
    for first, last, test_id in line_map:
        if first <= line <= last:
            return test_id
    return None
